let current = 'en';
export const t = (key) => STRINGS[current][key] ?? STRINGS.en[key] ?? key;

export function applyLang(lang, onChange) {
  current = STRINGS[lang] ? lang : 'en';
  document.documentElement.lang = current;
  document.querySelectorAll('[data-i18n]').forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-html]').forEach((node) => { node.innerHTML = t(node.dataset.i18nHtml); });
  document.querySelectorAll('.lang button').forEach((b) => b.classList.toggle('active', b.dataset.lang === current));
  try { localStorage.setItem('btY-lang', current); } catch (e) { /* storage unavailable */ }
  onChange?.(current);
}

export function initI18n(onChange) {
  let saved = 'en';
  try { saved = localStorage.getItem('btY-lang') || 'en'; } catch (e) { /* ignore */ }
  document.querySelectorAll('.lang button').forEach((b) => b.addEventListener('click', (ev) => {
    ev.stopPropagation();
    applyLang(b.dataset.lang, onChange);
  }));
  applyLang(saved, onChange);
}
